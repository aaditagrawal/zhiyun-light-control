import { createHash } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

// Builds the offline touch-rotatable G60 showcase: showcase.ts and Three.js
// (build-only) are bundled and minified, the actual g60.glb is embedded as
// base64, and the page is written as an Android APK asset, a fixture-only
// TypeScript string and a standalone viewer.html for browser QA.
const started = performance.now();
const root = resolve(import.meta.dir, '../..');
const glbPath = resolve(root, 'apps/android/assets/g60/g60.glb');
const documentPath = resolve(root, 'apps/android/src/showcase/document.ts');
const assetPath = resolve(root, 'apps/android/assets/g60/showcase.html');
const viewerPath = resolve(root, 'artifacts/showcase-20261025/viewer.html');

const glb = new Uint8Array(await Bun.file(glbPath).arrayBuffer());
const glbSha256 = createHash('sha256').update(glb).digest('hex');
const three = (await Bun.file(resolve(import.meta.dir, 'node_modules/three/package.json')).json()).version as string;

const result = await Bun.build({
  entrypoints: [resolve(import.meta.dir, 'showcase.ts')],
  target: 'browser',
  format: 'iife',
  minify: true,
});
if (!result.success) throw new Error(result.logs.join('\n'));
let bundle = await result.outputs[0].text();
// Inline script hazards: an end tag or comment opener would end or reparse
// the element. Escape end tags; fail on anything that cannot be rewritten.
bundle = bundle.replace(/<\/(script)/gi, '<\\/$1');
if (/<!--|<script/i.test(bundle)) throw new Error('Bundle contains an inline-script hazard');
// Base64 has no `<`, so the model data cannot close its element.
const model = Buffer.from(glb).toString('base64');

const background = [
  'radial-gradient(ellipse 105% 65% at 50% 30%,rgba(223,33,33,.95) 0%,rgba(216,34,33,.84) 20%,rgba(194,36,34,.6) 40%,rgba(150,23,22,.29) 60%,rgba(97,11,10,.075) 80%,rgba(97,11,10,0) 100%)',
  'radial-gradient(ellipse 120% 90% at 50% 40%,#8D1212 0%,#610B0A 45%,#290605 78%,#150505 100%)',
].join(',');
const csp = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src blob: data:; connect-src blob: data:";
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<meta http-equiv="Content-Security-Policy" content="${csp}">
<script>
// Inline pages are transparent over the app's own glow; mark them before first paint.
if(location.hash==='#inline'||location.hash==='#inline-reduce-motion'||window.__LIGHTTIME_INLINE__===true)document.documentElement.className='inline';
// Install before the main bundle so syntax errors also reach the native fallback.
window.addEventListener('error',function(event){if(!document.body?.classList.contains('ready'))window.ReactNativeWebView?.postMessage(JSON.stringify({type:'error',message:String(event.message).slice(0,200)}));});
window.ReactNativeWebView?.postMessage(JSON.stringify({type:'progress',phase:'bootstrap'}));
</script>
<title>G60</title>
<style>
html,body{margin:0;width:100%;height:100%;overflow:hidden;overscroll-behavior:none;background-color:#150505;background-image:${background};-webkit-tap-highlight-color:transparent;user-select:none;-webkit-user-select:none}
#halo{position:fixed;left:50%;top:50%;width:120vmin;height:120vmin;transform:translate(-50%,-50%) scale(.85);border-radius:50%;background:radial-gradient(circle,rgba(255,96,72,.34) 0%,rgba(223,33,33,.2) 32%,rgba(97,11,10,0) 68%);opacity:0;transition:opacity .9s ease,transform 1.2s cubic-bezier(.2,.8,.2,1);pointer-events:none}
#g60{position:fixed;inset:0;width:100%;height:100%;display:block;touch-action:none;opacity:0;transition:opacity .7s ease;cursor:grab}
#g60:active{cursor:grabbing}
#pulse{position:fixed;left:50%;top:50%;width:64px;height:64px;margin:-32px 0 0 -32px;border-radius:50%;border:3px solid rgba(255,227,224,.75);box-shadow:0 0 24px rgba(255,90,70,.7);animation:pulse 1.4s ease-in-out infinite;transition:opacity .4s ease;pointer-events:none}
@keyframes pulse{0%,100%{transform:scale(.8);opacity:.35}50%{transform:scale(1);opacity:1}}
.ready #g60{opacity:1}.ready #halo{opacity:1;transform:translate(-50%,-50%) scale(1)}.ready #pulse,.failed #pulse{opacity:0;animation:none}
@media (prefers-reduced-motion:reduce){#pulse{animation:none;opacity:.8}#g60,#halo{transition:none}}
html.inline,html.inline body{background:none transparent}.inline #halo,.inline #pulse{display:none}
</style></head><body>
<div id="halo"></div><div id="pulse"></div>
<canvas id="g60" role="img" aria-label="Rotatable G60 illustration. Drag to turn, pinch to zoom."></canvas>
<script id="g60-glb" type="application/octet-stream">${model}</script>
<script>${bundle}</script>
</body></html>
`;
const htmlSha256 = createHash('sha256').update(html).digest('hex');

const source = `// Generated by scripts/model-g60/showcase-build.ts — do not edit by hand.
// Rebuild: cd scripts/model-g60 && bun install --frozen-lockfile && bun run build:showcase
// Fixture-only HTML export. Android loads the matching bundled showcase.html asset.
// Variants: no hash (fullscreen), #reduce-motion, #inline and #inline-reduce-motion
// (transparent page, no halo or loading pulse). Fixtures without a hash may inject
// window.__LIGHTTIME_INLINE__ = true and window.__LIGHTTIME_REDUCED_MOTION__ = true.
// Renderer: scripts/model-g60/showcase.ts with ruby.ts lighting; Three.js ${three}
// (MIT) is bundled at build time only and is not an app dependency.
// Model: apps/android/assets/g60/g60.glb, ${glb.byteLength} bytes, sha256 ${glbSha256},
// embedded as base64. No network, remote fonts or CDNs. The model is an
// illustration and never reflects or changes a physical light.
// Messages to native: {type:'ready'}, {type:'error',message}, {type:'state',spinning}, {type:'progress',phase},
// {type:'interaction'}. Commands: window.G60Showcase.command('front'|'back'|'reset'|
// 'spin'|'pause'|'resume'|'dispose'), or a message {type:'lighttime-showcase-command',action}.
// Document: ${html.length} characters, sha256 ${htmlSha256}.
export const SHOWCASE_MODEL_SHA256 = '${glbSha256}';
export const SHOWCASE_HTML: string = ${JSON.stringify(html)};
`;

await mkdir(dirname(documentPath), { recursive: true });
await mkdir(dirname(viewerPath), { recursive: true });
await Bun.write(documentPath, source);
await Bun.write(assetPath, html);
await Bun.write(viewerPath, html);
const kib = (n: number) => `${(n / 1024).toFixed(0)} KiB`;
console.log(`Showcase: ${kib(html.length)} HTML (script ${kib(bundle.length)}, model ${kib(model.length)} base64), document.ts ${kib(source.length)}, ${Math.round(performance.now() - started)} ms`);
console.log(`  ${documentPath}\n  ${viewerPath}`);
